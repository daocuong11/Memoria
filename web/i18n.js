  var lang = localStorage.getItem("memoria_lang");
  // Default SELALU English (produk internasional). Bahasa Indonesia hanya
  // jika dipilih eksplisit di Pengaturan -> Language.
  if (lang !== "id" && lang !== "en") lang = "en";
  function t(key) {
    var s = lang === "id" ? (ID[key] || key) : key;
    for (var i = 1; i < arguments.length; i++) {
      s = s.split("{" + (i - 1) + "}").join(String(arguments[i]));
    }
    return s;
  }
  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    root.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
    });
    root.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
    root.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
  }
  function setLang(l) {
    if (l !== "id" && l !== "en") return;
    lang = l;
    localStorage.setItem("memoria_lang", l);
    apply();
    window.dispatchEvent(new CustomEvent("memoria:lang"));
  }
